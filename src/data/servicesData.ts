/** Helper function to convert an InstallableGame into a cart Product */
export function gameToProduct(game: InstallableGame): Product {
  return {
    id: `game-install-${game.id}`,
    name: `${game.title} (In-Shop Install)`,
    category: 'discs',
    brand: game.platformCategory,
    condition: 'Brand New',
    priceGHS: game.installPriceGHS,
    originalPriceGHS: game.originalPriceGHS,
    rating: game.rating,
    reviewsCount: 42,
    inStock: true,
    stockCount: 99,
    badge: game.badge || 'Digital Install',
    swapEligible: false,
    image: game.coverImage,
    gallery: [game.coverImage],
    kind: 'game_install',
    installMeta: {
      platformCategory: game.platformCategory,
      sizeGB: game.sizeGB,
      requirements: [
        game.systemRequirements.os,
        game.systemRequirements.ram,
        game.systemRequirements.storage,
        game.systemRequirements.gpuOrProcessor,
      ],
    },
    specs: {
      storage: game.systemRequirements.storage,
      ram: game.systemRequirements.ram,
      processor: game.systemRequirements.gpuOrProcessor,
      compatibility: game.platforms.join(', '),
      edition: game.platformCategory,
    },
    description: `Digital Game Installation for ${game.platforms.join(', ')}. Requirements: ${game.systemRequirements.os}, ${game.systemRequirements.ram} RAM, ${game.systemRequirements.storage} Storage. ${game.details}`,
  };
}

